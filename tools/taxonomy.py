#!/usr/bin/env python3
"""Generate one page per category (category/<slug>.qmd) and per tag (tag/<slug>.qmd).

Runs automatically before every `quarto render` / `quarto preview` (see
`pre-render` in _quarto.yml). It reads `categories:` and `tags:` from the front
matter of every posts/*/index.qmd, so a new category or tag gets its page the
next time the site is built. The generated folders are git-ignored.
"""
import glob
import html
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "tools"))
from frontmatter import read_front_matter, slugify  # noqa: E402

# Optional one-line descriptions shown under a category's title.
CATEGORY_BLURBS_FILE = os.path.join(ROOT, "categories.yml")

# Every category gets one of the six hues of the palette (assets/theme-*.scss).
# Known categories have a fixed hue; new ones get the next hue in HUE_ORDER.
HUES = {
    "Deep Learning": "cyan",
    "Geometric Deep Learning": "violet",
    "Climate & Weather": "blue",
    "AI Societal Impact": "brown",
    "Books": "amber",
    "Philosophy (sort of)": "teal",
}
HUE_ORDER = ["cyan", "teal", "blue", "violet", "brown", "amber"]
CATEGORY_CSS = os.path.join(ROOT, "assets", "categories.css")


def category_css(names):
    used, lines = {}, ["/* generated by tools/taxonomy.py on every build: one hue per category */"]
    free = iter([h for h in HUE_ORDER * 10])
    for name in sorted(names, key=lambda n: (n not in HUES, n.lower())):
        hue = HUES.get(name) or next(free)
        used[name] = hue
        lines.append(f'[data-cat="{slugify(name)}"] {{ --hue: var(--h-{hue}); --hue-deco: var(--h-{hue}-deco); '
                     f'--hue-wash: var(--h-{hue}-wash); }}')
    return "\n".join(lines) + "\n"


def load_blurbs():
    if not os.path.exists(CATEGORY_BLURBS_FILE):
        return {}
    blurbs = {}
    for line in open(CATEGORY_BLURBS_FILE, encoding="utf-8"):
        m = re.match(r'^\s*"?([^":#][^":]*?)"?\s*:\s*(.+?)\s*$', line)
        if m and not line.lstrip().startswith("#"):
            blurbs[m.group(1).strip()] = m.group(2).strip().strip('"')
    return blurbs


def page(kind, name, blurb=""):
    field = "categories" if kind == "category" else "tags"
    label = "Category" if kind == "category" else "Tag"
    lines = [
        "---",
        f"title: {json.dumps(name, ensure_ascii=False)}",
        f"pagetitle: {json.dumps(label + ': ' + name, ensure_ascii=False)}",
    ]
    if blurb:
        lines.append(f"description: {json.dumps(blurb, ensure_ascii=False)}")
    lines += [
        f"taxonomy-kind: {label}",
        "page-layout: full",
        "dv-no-title: true",
        "body-classes: dv-wide",
        "search: false",
        "toc: false",
        "listing:",
        "  id: posts",
        '  contents: "../posts/*/index.qmd"',
        "  template: ../assets/listing-posts.ejs",
        "  template-params:",
        "    count: true",
        "    root: \"../\"",
        f"    feed: {json.dumps(slugify(name) + '.xml')}",
        "  sort: \"date desc\"",
        "  fields: [title, date, description, image, categories, tags, reading-time, lang]",
        "  include:",
        f"    {field}: {json.dumps(name, ensure_ascii=False)}",
        "  feed: true",
        "---",
        "",
        ("::: {.taxonomy-head data-cat=\"" + slugify(name) + "\"}" if kind == "category" else "::: {.taxonomy-head}"),
        f"[{label}]{{.kicker data-i18n=\"{kind}\"}}",
        "",
        f"# {name}",
        "",
    ]
    if blurb:
        lines += [f"[{blurb}]{{.blurb}}", ""]
    lines += [
        "[All topics](../topics.qmd){.all-topics data-i18n=\"alltopics\"}",
        ":::",
        "",
    ]
    return "\n".join(lines) + "\n"


LATEST_FILE = os.path.join(ROOT, "_latest.md")


def opening(body, min_words=130, max_words=230):
    """The first paragraphs of a post, verbatim, for the home page."""
    paras, cur, fence = [], [], None
    for line in body.split("\n") + [""]:
        st = line.strip()
        if fence:
            if st.startswith(fence):
                fence = None
            continue
        if st.startswith("```") or st.startswith(":::"):
            fence = st[:3]
            if cur:
                paras.append(" ".join(cur)); cur = []
            continue
        if not st:
            if cur:
                paras.append(" ".join(cur)); cur = []
            continue
        cur.append(st)
    keep, words = [], 0
    for p in paras:
        if re.match(r"^(#|>|!\[|<|\||\[\^|-{3,}|\$\$)", p):
            continue
        p = re.sub(r"\[\^[^\]]+\]", "", p)          # footnote markers
        p = re.sub(r"\s?\[-?@[^\]]+\]", "", p)       # citations need the bibliography
        p = re.sub(r"\s?\(@[^)]+\)", "", p)
        n = len(p.split())
        if words + n > max_words and keep:
            # cut this paragraph at a sentence end, if one comes early enough
            room = max_words - words
            cut = None
            for m in re.finditer(r"[.!?…](\s)", p):
                prefix = p[: m.start() + 1]
                if len(prefix.split()) > room:
                    break
                if prefix.count("[") == prefix.count("]") and prefix.count("(") == prefix.count(")"):
                    cut = prefix
            if cut and len(cut.split()) >= 25:
                keep.append(cut + " …")
            break
        keep.append(p)
        words += n
        if words >= min_words:
            break
    return keep


def latest_feature(posts):
    """Markdown for the featured latest post on the home page (included by index.qmd)."""
    if not posts:
        return ""
    qmd, fm, body = max(posts, key=lambda x: str(x[1].get("date", "")))
    folder = os.path.basename(os.path.dirname(qmd))
    href = f"posts/{folder}/index.html"
    cats = fm.get("categories", []) or []
    lang = str(fm.get("lang") or "en")[:2].lower()
    esc = lambda t: html.escape(str(t), quote=True)
    first = slugify(cats[0]) if cats else "x"
    out = ["```{=html}",
           f'<section class="dv-feature" data-cat="{first}" data-lang="{lang}" aria-labelledby="dv-feature-title">']
    if fm.get("image"):
        out.append(f'<a class="dv-feature-img" href="{href}" tabindex="-1" aria-hidden="true">'
                   f'<img src="posts/{folder}/{esc(fm["image"])}" alt="" decoding="async"></a>')
    out.append('<div class="dv-feature-text">')
    out.append('<div class="dv-kicker"><span class="dv-kicker-label" data-i18n="latest">Latest post</span>'
               + "".join(f'<a class="dv-cat" data-cat="{slugify(c)}" href="category/{slugify(c)}.html">{esc(c)}</a>' for c in cats)
               + "</div>")
    out.append(f'<h2 class="dv-feature-title no-anchor" id="dv-feature-title"><a href="{href}">{esc(fm.get("title", ""))}</a></h2>')
    date = str(fm.get("date", ""))[:10]
    out.append(f'<div class="dv-item-meta"><time datetime="{date}" data-fmt="long">{date}</time>'
               f'<span class="dv-langbadge" data-lang="{lang}">{lang}</span></div>')
    out += ["```", "", f"::: {{.dv-feature-opening lang=\"{lang}\"}}"]
    for p in opening(body):
        out += [p, ""]
    out += [":::", "", "```{=html}",
            f'<a class="dv-readmore" href="{href}" data-i18n="readpost">Read the post &rarr;</a>',
            "</div></section>", "```", ""]
    return "\n".join(out)


def write_if_changed(path, content):
    if os.path.exists(path) and open(path, encoding="utf-8").read() == content:
        return
    with open(path, "w", encoding="utf-8") as f:
        f.write(content)


def main():
    cats, tags, posts = {}, {}, []
    for qmd in sorted(glob.glob(os.path.join(ROOT, "posts", "*", "index.qmd"))):
        fm = read_front_matter(qmd)
        if fm.get("draft") in (True, "true", "yes"):
            continue
        text = open(qmd, encoding="utf-8").read()
        body = re.sub(r"^---\s*\n.*?\n---\s*\n", "", text, count=1, flags=re.S)
        posts.append((qmd, fm, body))
        for c in fm.get("categories", []) or []:
            cats.setdefault(slugify(c), c)
        for t in fm.get("tags", []) or []:
            tags.setdefault(slugify(t), t)

    write_if_changed(CATEGORY_CSS, category_css(cats.values()))
    write_if_changed(LATEST_FILE, latest_feature(posts))
    blurbs = load_blurbs()
    for kind, names in (("category", cats), ("tag", tags)):
        outdir = os.path.join(ROOT, kind)
        os.makedirs(outdir, exist_ok=True)
        wanted = set()
        for slug, name in names.items():
            fn = os.path.join(outdir, slug + ".qmd")
            wanted.add(fn)
            write_if_changed(fn, page(kind, name, blurbs.get(name, "") if kind == "category" else ""))
        for stale in glob.glob(os.path.join(outdir, "*.qmd")):
            if stale not in wanted:
                os.remove(stale)
    print(f"taxonomy: {len(cats)} categories, {len(tags)} tags")


if __name__ == "__main__":
    main()
